"""Build the course index: the chapter table in README.md and a data file for the course hub.

Standard library only. Reads curriculum/<language>.json, state/progress.json and, for each
chapter folder, meta.json and video/render.json.

    python3 tools/build_course_index.py                      # update README.md
    python3 tools/build_course_index.py --hub-out hub.csv    # also write the hub data (.csv or .json)
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO_URL = "https://github.com/DipurajThapa/CourseVideos/blob/main/"
START, END = "<!-- course-index:start -->", "<!-- course-index:end -->"
STATUS_LABEL = {"pending": "Pending", "in_progress": "In progress", "blocked": "Blocked",
                "in_review": "Ready for review", "approved": "Approved",
                "changes_requested": "Changes requested"}
FIELDS = ["number", "id", "module", "module_title", "title", "type", "badge", "status",
          "video_minutes", "xp_total", "lesson_url", "video_url"]


def load_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def chapter_rows(language: str = "python") -> list[dict]:
    curriculum = load_json(ROOT / "curriculum" / f"{language}.json")
    progress = load_json(ROOT / "state" / "progress.json").get("chapters", {})
    rows = []
    for module in curriculum.get("modules", []):
        for ch in module.get("chapters", []):
            folder = ROOT / "chapters" / language / f"{ch['number']:02d}-{ch['slug']}"
            rel = folder.relative_to(ROOT).as_posix()
            meta = load_json(folder / "meta.json")
            render = load_json(folder / "video" / "render.json")
            doc = "project.md" if ch.get("type") == "project" else "lesson.md"
            xp = meta.get("xp", {})
            xp_total = sum(v for v in xp.values() if isinstance(v, (int, float))) if xp else ""
            seconds = render.get("duration_seconds")
            video = folder / "video" / "chapter.mp4"
            rows.append({
                "number": ch["number"],
                "id": ch["id"],
                "module": module.get("id", ""),
                "module_title": module.get("title", ""),
                "title": ch["title"],
                "type": "Boss level" if ch.get("type") == "project" else "Lesson",
                "badge": meta.get("badge") or ch.get("badge", ""),
                "status": STATUS_LABEL.get(progress.get(ch["id"], {}).get("status", "pending"), "Pending"),
                "video_minutes": round(seconds / 60, 2) if seconds else "",
                "xp_total": xp_total,
                "lesson_url": REPO_URL + f"{rel}/{doc}" if (folder / doc).exists() else "",
                "video_url": REPO_URL + f"{rel}/video/chapter.mp4" if video.exists() and seconds else "",
                "_doc": f"{rel}/{doc}" if (folder / doc).exists() else "",
                "_video": f"{rel}/video/chapter.mp4" if video.exists() and seconds else "",
                "_seconds": seconds,
            })
    return rows


def mmss(seconds) -> str:
    if not seconds:
        return ""
    s = int(round(seconds))
    return f"{s // 60}:{s % 60:02d}"


def readme_block(rows: list[dict]) -> str:
    done = sum(1 for r in rows if r["status"] in ("Ready for review", "Approved"))
    total_s = sum(r["_seconds"] or 0 for r in rows)
    lines = [START, "",
             f"{done} of {len(rows)} chapters are finished, with {int(total_s // 3600)} h {int(total_s % 3600 // 60)} min of video in total.",
             "This table is generated by `tools/build_course_index.py`.", ""]
    module = None
    for r in rows:
        if r["module"] != module:
            module = r["module"]
            lines += ["", f"### {r['module']}: {r['module_title']}", "",
                      "| # | Chapter | Type | Badge | Status | Video |", "|---|---|---|---|---|---|"]
        title = f"[{r['title']}]({r['_doc']})" if r["_doc"] else r["title"]
        video = f"[{mmss(r['_seconds'])}]({r['_video']})" if r["_video"] else ""
        lines.append(f"| {r['number']} | {title} | {r['type']} | {r['badge']} | {r['status']} | {video} |")
    lines += ["", END]
    return "\n".join(lines)


def update_readme(rows: list[dict]) -> bool:
    path = ROOT / "README.md"
    text = path.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print("README.md has no course-index markers; nothing changed", file=sys.stderr)
        return False
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _m: readme_block(rows), text, flags=re.S)
    if new != text:
        path.write_text(new, encoding="utf-8")
        return True
    return False


def write_hub(rows: list[dict], out: Path) -> None:
    clean = [{k: r[k] for k in FIELDS} for r in rows]
    if out.suffix == ".json":
        out.write_text(json.dumps(clean, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        return
    with out.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(clean)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--language", default="python")
    parser.add_argument("--hub-out", type=Path, help="write the hub data to this .csv or .json file")
    args = parser.parse_args()
    rows = chapter_rows(args.language)
    changed = update_readme(rows)
    print(f"README.md {'updated' if changed else 'unchanged'}; {len(rows)} chapters")
    if args.hub_out:
        write_hub(rows, args.hub_out)
        print(f"hub data written to {args.hub_out}")


if __name__ == "__main__":
    main()
